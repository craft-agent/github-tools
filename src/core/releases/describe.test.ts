import { describe, expect, test } from "bun:test"
import {
  RELEASE_COMMIT,
  gitRefTagRule,
  rawRelease,
  releaseByTagRule,
  releasesPageRule,
  restNotFound,
} from "../../testing/releases-fixtures"
import { queryOf } from "../../testing/setup-fixtures"
import { repositoryRule } from "../../testing/write-fixtures"
import { MAX_FACTS, MAX_HEADLINE_LENGTH, MAX_LABEL_LENGTH } from "../describe"
import { DESCRIBE_CASES, TAG, describeCase, noReleaseRules, type DescribeCase } from "./describe.fixtures"

/** The methods of a `gh api` call that change something, and the `gh release` commands that do. */
const WRITE_METHODS = ["POST", "PUT", "PATCH", "DELETE"]
const WRITE_COMMANDS = ["create", "edit", "delete"]

const NOT_WRITABLE = repositoryRule({ permission: "READ" })
const named = (text: string, name = `Release ${TAG}`) => ({ text, values: { name } })
const on = (label: string) => ({ label, value: { text: "On" } })
const off = (label: string) => ({ label, value: { text: "Off" } })
const state = (word: string) => ({ label: "State", value: { text: word } })

describe("github_release_create", () => {
  const headline = { text: "About to create a draft release for the tag {tag}", values: { tag: "v2.0.0" } }

  test("a tag alone is a headline", async () => {
    expect(await describeCase(DESCRIBE_CASES.createDefaults)).toEqual({ headline, facts: [] })
  })

  test("every piece: the target, generated notes, the flag, the title and the notes verbatim", async () => {
    expect(await describeCase(DESCRIBE_CASES.createFull)).toEqual({
      headline,
      facts: [
        { label: "Tag target", value: "main" },
        { label: "Notes", value: { text: "Generated by GitHub" } },
        on("Prerelease"),
        { label: "Title", value: "Two" },
      ],
      text: { label: "Release notes", body: "What is new" },
    })
  })

  test("a commit target and a final release", async () => {
    expect((await describeCase(DESCRIBE_CASES.createFromCommit))?.facts).toEqual([
      { label: "Tag target", value: RELEASE_COMMIT },
      off("Prerelease"),
    ])
  })

  const create = DESCRIBE_CASES.createFull
  const sha = { object: { type: "commit", sha: RELEASE_COMMIT } }
  test.each([
    ["a bad tag", { tag: "a..b" }, create.rules],
    [
      "a tag that has a published release",
      create.args,
      [repositoryRule(), releaseByTagRule("v2.0.0", rawRelease("v2.0.0"))],
    ],
    [
      "a tag that has a draft release",
      { tag: "v2.0.0" },
      [
        repositoryRule(),
        releaseByTagRule("v2.0.0", null),
        releasesPageRule(1, [rawRelease("v2.0.0", { draft: true })]),
      ],
    ],
    [
      "a target for a tag that exists",
      create.args,
      [repositoryRule(), ...noReleaseRules("v2.0.0"), gitRefTagRule("v2.0.0", sha)],
    ],
    [
      "a target branch that does not exist",
      { tag: "v2.0.0", target: "nope" },
      [
        repositoryRule(),
        ...noReleaseRules("v2.0.0"),
        restNotFound("git/ref/tags/v2.0.0"),
        restNotFound("branches/nope"),
      ],
    ],
    ["a repository the viewer cannot write to", create.args, [NOT_WRITABLE, ...create.rules.slice(1)]],
  ])("%s: no description", async (_name, args, rules) => {
    expect(await describeCase({ ...create, args, rules })).toBeUndefined()
  })
})

describe("every description", () => {
  const cases = Object.values<DescribeCase>(DESCRIBE_CASES)

  test.each(cases.map((item) => [item.name, item] as const))("%s: is within the budgets", async (_name, item) => {
    const description = await describeCase(item)
    expect(description).toBeDefined()
    expect(Array.from(description!.headline!.text).length).toBeLessThanOrEqual(MAX_HEADLINE_LENGTH)
    expect(description!.facts.length).toBeLessThanOrEqual(MAX_FACTS)
    for (const { label } of description!.facts) expect(Array.from(label).length).toBeLessThanOrEqual(MAX_LABEL_LENGTH)
  })

  test.each(cases.map((item) => [item.name, item] as const))(
    "%s: is the same when asked twice",
    async (_name, item) => {
      expect(await describeCase(item)).toEqual(await describeCase(item))
    },
  )

  test.each(cases.map((item) => [item.name, item] as const))("%s: only reads", async (_name, item) => {
    let calls: string[][] = []
    await describeCase(item, (seen) => (calls = seen))
    const isWrite = (args: string[]) =>
      queryOf(args).startsWith("mutation") ||
      WRITE_METHODS.some((method) => args.includes(method)) ||
      (args[0] === "release" && WRITE_COMMANDS.includes(args[1] ?? ""))
    expect(calls.length).toBeGreaterThan(0)
    expect(calls.filter(isWrite)).toEqual([])
  })
})
